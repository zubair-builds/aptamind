/**
 * Sub-national places (US states, Canadian provinces) and major hiring cities, each mapped to its
 * country. Used to normalise listed locations ("San Francisco, CA", "Toronto, ON") and to resolve
 * restrictions stated with places rather than countries ("must be based in California").
 */

export interface SubdivisionDef {
  country: string;
  /** Postal abbreviation, e.g. `CA`, `ON`. */
  code: string;
  name: string;
}

export interface CityDef {
  name: string;
  country: string;
  /** Subdivision abbreviation when the city is in a US state / Canadian province. */
  subdivision?: string;
  aliases?: readonly string[];
}

