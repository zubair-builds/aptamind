/**
 * Generates docs/architecture/capability-idempotency.md — every registered production
 * capability with its side-effect flag, retry default and idempotency strategy/proof — from
 * the capability definitions themselves, so the matrix cannot drift from the code.
 *   pnpm docs:capabilities
 */
import { writeFileSync } from 'node:fs';
import { marketCapabilities } from '@aptamind/market';
import { professionalCapabilities } from '@aptamind/professional';
import type { AnyCapability } from '@aptamind/workflow-sdk';
import { capabilityKey, executionContractViolation } from '@aptamind/workflow-sdk';
import { genericCapabilities } from '@aptamind/workflow-nodes';
import { forEachCapability } from '@aptamind/workflows';

const groups: Array<[string, AnyCapability[]]> = [
  ['Generic runtime (engine-implemented)', [forEachCapability as AnyCapability]],
  ['Generic capabilities (`packages/workflow-nodes`)', genericCapabilities],
  ['Market capabilities (`packages/market/src/workflow-nodes`)', marketCapabilities],
  ['Professional capabilities (`packages/professional/src/workflow-nodes`)', professionalCapabilities],
];

const esc = (s: string) => s.replace(/\|/g, '\\|');
const IN_PLACE_MARKER = 'Changed in place';
const lines = [
  '# Capability idempotency matrix',
  '',
  '> Generated by `pnpm docs:capabilities` from the capability definitions. Do not edit by hand.',
  '',
  'The runtime executes nodes **at least once** (crash, lease takeover, lost acknowledgement,',
  'retry). Every capability therefore declares how it stays correct under re-execution, and',
  'registration rejects an invalid or ambiguous declaration (`executionContractViolation`):',
  '',
  '| Strategy   | Meaning                                                                                   |',
  '| ---------- | ----------------------------------------------------------------------------------------- |',
  '| `pure`     | No durable side effects (read-only I/O; content-addressed artifact writes are allowed).    |',
  '| `key`      | Side effects keyed on `ctx.idempotencyKey`; a re-execution reuses what the first one did. |',
  '| `natural`  | Side effects idempotent by construction (deterministic ids, unique keys, replay markers). |',
  '| `no_retry` | Never re-executed automatically (no retries; a lease takeover fails the node).            |',
  '',
];
let invalid = 0;
for (const [title, caps] of groups) {
  lines.push(
    `## ${title}`,
    '',
    '| Capability | Side effects | Retryable | Strategy | Proof / implementation |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const c of [...caps].sort((a, b) => capabilityKey(a).localeCompare(capabilityKey(b)))) {
    const e = c.execution;
    if (executionContractViolation(e)) invalid += 1;
    const proof =
      e.idempotencyProof ??
      (e.idempotency === 'pure'
        ? 'No durable domain side effects (read-only I/O; any artifact write is content-addressed).'
        : '—');
    lines.push(
      `| \`${capabilityKey(c)}\` | ${e.sideEffects ? 'yes' : 'no'} | ${e.retryable ? 'yes' : 'no'} | \`${e.idempotency}\` | ${esc(proof)} |`,
    );
  }
  lines.push('');
  // A published version changed in place (an accepted exception to "new behaviour = new
  // version") says so in its description, starting with IN_PLACE_MARKER; list those here.
  const inPlace = [...caps]
    .sort((a, b) => capabilityKey(a).localeCompare(capabilityKey(b)))
    .flatMap((c) => {
      const at = c.description.indexOf(IN_PLACE_MARKER);
      return at < 0 ? [] : [`- \`${capabilityKey(c)}\`: ${c.description.slice(at).trim()}`];
    });
  if (inPlace.length) lines.push('Versions changed in place:', '', ...inPlace, '');
}
if (invalid) throw new Error(`${invalid} capabilities violate the execution contract`);
writeFileSync('docs/architecture/capability-idempotency.md', `${lines.join('\n')}\n`);
console.log('wrote docs/architecture/capability-idempotency.md');
