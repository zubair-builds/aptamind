/**
 * Generates docs/architecture/data-model.md from the collection specs (names, descriptions,
 * schema versions, indexes and their rationale) so the document cannot drift from the code.
 *   pnpm docs:data-model
 */
import { writeFileSync } from 'node:fs';
import type { CollectionSpec } from '@aptamind/db';
import { marketCollections } from '@aptamind/market';
import { professionalCollections } from '@aptamind/professional';
import { artifactsCollection } from '@aptamind/storage';
import { workflowCollections } from '@aptamind/workflows';

const groups: Array<[string, CollectionSpec<never>[]]> = [
  ['Workflow runtime (generic)', workflowCollections as never],
  ['Artifacts (generic)', [artifactsCollection] as never],
  ['Market domain', marketCollections as never],
  ['Professional domain', professionalCollections as never],
];

const lines: string[] = [
  '# Data model',
  '',
  '> Generated by `pnpm docs:data-model` from the collection specs in code. Do not edit by hand;',
  '> edit the `defineCollection(...)` specs and regenerate.',
  '',
  'All important documents carry `schemaVersion`, `createdAt` and `updatedAt`. Derived intelligence also',
  'records `logicVersion` / `policyVersion` / `taxonomyVersion` (and prompt/model versions when AI was used).',
  'Documents are validated with Zod at the application boundary; key collections also carry a MongoDB',
  '`$jsonSchema` validator (`validationLevel: moderate`).',
  '',
  '## Uniqueness assumptions',
  '',
  '| Collection | Unique key | Why |',
  '| --- | --- | --- |',
];
for (const [, specs] of groups) {
  for (const s of specs) {
    for (const i of s.indexes.filter((x) => x.options.unique)) {
      lines.push(
        `| \`${s.name}\` | \`${JSON.stringify(i.key)}\`${i.options.partialFilterExpression ? ` (partial: \`${JSON.stringify(i.options.partialFilterExpression)}\`)` : ''} | ${i.rationale} |`,
      );
    }
  }
}
for (const [title, specs] of groups) {
  lines.push('', `## ${title}`);
  for (const s of specs) {
    lines.push(
      '',
      `### \`${s.name}\` (schema v${s.schemaVersion})`,
      '',
      s.description,
      '',
      '| Index | Keys | Options | Rationale |',
      '| --- | --- | --- | --- |',
    );
    lines.push(
      '| `_id_` | `{"_id":1}` | unique | Primary key (prefixed string ids; deterministic where idempotency requires). |',
    );
    for (const i of s.indexes) {
      const { name, ...opts } = i.options;
      lines.push(
        `| \`${name}\` | \`${JSON.stringify(i.key)}\` | ${Object.keys(opts).length ? `\`${JSON.stringify(opts)}\`` : '—'} | ${i.rationale} |`,
      );
    }
    if (s.validator) lines.push('', `MongoDB validator: \`${JSON.stringify(s.validator)}\``);
  }
}
writeFileSync(new URL('../docs/architecture/data-model.md', import.meta.url), lines.join('\n') + '\n');
console.log('wrote docs/architecture/data-model.md');
